async function cash(id, amount = 2750000, paid = 0, request = randomUUID(), kind = 'REGISTRATION', ack = true) {
  return scalar(`select record_counter_cash($1,$2,$3,$4,$5,$6,current_date+30,'Synthetic receipt')`, [request,kind,id,amount,paid,ack])
}
test('deposit and balance share one invoice; retry cannot duplicate money, identity or enrollment', async () => {
  const app = await application(), request = randomUUID()
  const first = await cash(app,2750000,0,request)
  assert.equal(first.state,'DEPOSIT_PAID')
  assert.equal(first.remaining,2750000)
  assert.equal(await scalar('select status from registration_applications where id=$1',[app]),'COMPLETED')
  assert.equal(Number(await scalar('select count(*) from student_placement_cases where registration_application_id=$1 and status=\'UNASSIGNED\'',[app])),1)
  assert.equal(Number(await scalar('select count(*) from enrollments where student_id=(select linked_student_id from registration_applications where id=$1)',[app])),0)
  assert.equal((await cash(app,2750000,0,request)).result,'duplicate')
  await fails(() => cash(app,5500000,0,request),/CASH_REQUEST_CONFLICT/)
  await fails(() => cash(app,2750000,0),/CASH_STALE_BALANCE/)
  const last = await cash(app,2750000,2750000)
  assert.equal(last.state,'PAID'); assert.equal(last.invoice_id,first.invoice_id)
  assert.equal(Number(await scalar('select count(*) from counter_cash_receipts where application_id=$1',[app])),2)
  assert.equal(Number(await scalar('select count(*) from invoices where registration_application_id=$1',[app])),1)
  assert.equal(Number(await scalar('select outstanding_balance from invoice_receivables where invoice_id=$1',[first.invoice_id])),0)
  assert.equal(Number(await scalar('select count(*) from students where full_name=\'Synthetic Cash Student\'')),1)
  await db.exec('set constraints all immediate')
})
test('acknowledgement, threshold, whole amounts, remaining balance and identity are enforced in the database', async () => {
  const app = await application()
  await fails(() => cash(app,2750000,0,randomUUID(),'REGISTRATION',false),/CASH_ACK_REQUIRED/)
  await fails(() => cash(app,1),/CASH_BELOW_THRESHOLD/)
  await fails(() => cash(app,5500001),/CASH_EXCEEDS_BALANCE/)
  await fails(() => cash(app,2750000.5),/CASH_INVALID/)
  const full = await cash(app,5500000)
  assert.equal(full.state,'PAID')
  await fails(() => cash(app,1,5500000),/CASH_EXCEEDS_BALANCE/)
  const duplicate = await application()
  await fails(() => cash(duplicate),/REGISTRATION_REVIEW_REQUIRED/)
  assert.equal(Number(await scalar('select count(*) from counter_cash_receipts where application_id=$1',[duplicate])),0)
})
