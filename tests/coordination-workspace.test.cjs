const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')

const navigation = fs.readFileSync('app/admin/navigation.ts', 'utf8')
const workspace = fs.readFileSync('app/admin/coordination/Workspace.tsx', 'utf8')
const weeklyBoard = fs.readFileSync('app/admin/coordination/WeeklyBoard.tsx', 'utf8')
const data = fs.readFileSync('app/admin/coordination/data.ts', 'utf8')
const actions = fs.readFileSync('app/admin/students/placement-actions.ts', 'utf8')
const migration = fs.readFileSync('supabase/migrations/20261021013000_placement_eligibility_contract.sql', 'utf8')
const waitingQueue = fs.readFileSync('supabase/migrations/20261021112000_waiting_queue_excludes_enrolled.sql', 'utf8')
const students = fs.readFileSync('app/admin/students/page.tsx', 'utf8')
const windows = fs.readFileSync('supabase/migrations/20261024010000_placement_time_windows.sql', 'utf8')
const windowFields = fs.readFileSync('app/admin/coordination/time-window-fields.tsx', 'utf8')

test('teaching shifts and schedule share one training entry', () => {
  assert.match(navigation, /Ca dạy & Lịch học/)
  assert.equal((navigation.match(/studentTab: 'coordination'/g) || []).length, 1)
  assert.equal(navigation.includes("studentTab: 'teaching-shifts'"), false)
  assert.equal(navigation.includes("studentTab: 'schedule'"), false)
  assert.match(workspace, /Chờ vào ca/)
  assert.match(workspace, /Danh sách ca/)
  assert.match(workspace, /Lịch tuần/)
  assert.match(workspace, /Hôm nay/)
  assert.match(weeklyBoard, /Đổi riêng buổi này/)
  assert.match(workspace, /WeeklyDashboard params/)
  assert.equal(workspace.includes('loadWeek('), false)
  assert.match(workspace, /Đổi lịch định kỳ từ ngày/)
  assert.match(workspace, /Xếp lịch học/)
  assert.match(workspace, /Mỗi ca định kỳ là một thứ/)
  assert.equal(workspace.includes('trang lựa chọn này'), false)
  assert.equal(students.includes('trang lựa chọn này'), false)
  assert.equal(students.includes('list_placement_class_options'), false)
})

test('placement search and confirmation share one decision and do not reuse a past date', async () => {
  const { proposedParticipationDate, placementStaffMessage } = await import('../app/admin/coordination/rules.ts')
  assert.equal(proposedParticipationDate('2020-01-01', '2026-10-21'), '2026-10-21')
  assert.equal(proposedParticipationDate('2026-11-02', '2026-10-21'), '2026-11-02')
  assert.match(placementStaffMessage('PLACEMENT_START_PAST'), /đã qua/)
  assert.equal(placementStaffMessage('duplicate key value violates unique constraint'), null)
  assert.match(migration, /placement_shift_decision/)
  assert.match(migration, /list_placement_candidates/)
  assert.match(migration, /PLACEMENT_START_PAST/)
  assert.match(migration, /placement_shift_decision\(p_placement, p_class, p_start, null\)/)
  assert.match(waitingQueue, /open_enrollment.status in \('ACTIVE', 'PAUSED'\)/)
  assert.match(waitingQueue, /status = 'SCHEDULED'/)
  assert.match(actions, /PLACEMENT_START_PAST/)
  assert.match(actions, /return_to/)
  assert.match(data, /list_placement_candidates/)
  assert.match(data, /placement_time_windows/)
  assert.match(windows, /create table public.placement_time_windows/)
  assert.match(windows, /placement_window_fit/)
  assert.equal(windows.includes('availability_note'), true)
  assert.match(windowFields, /Áp dụng giờ này cho các buổi còn lại/)
  assert.match(data, /coordination load failed/)
  assert.equal(data.includes('list_placement_class_options'), false)
})
