// Browser verification of real components/actions/SQL with synthetic identities.
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const { spawn } = require('node:child_process')
const { createRequire } = require('node:module')
const { ids } = require('../../tests/helpers/video-link-db-fixture.cjs')
const tools = createRequire(path.join(process.env.VIBE_VIDEO_TEST_TOOLS, 'package.json'))
const { chromium } = tools('playwright-core')

async function main() {
  const child = spawn(process.execPath, ['scripts/verification/academic-video-links-harness.cjs'], { env: process.env, stdio: ['ignore', 'pipe', 'inherit'] })
  let browser
  const folder = path.resolve('docs/verification/academic-video-links')
  fs.mkdirSync(folder, { recursive: true })
  const checks = []
  try {
    await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Harness startup timeout')), 30000)
      child.stdout.on('data', value => { if (value.toString().includes('SYNTHETIC HARNESS')) { clearTimeout(timer); resolve() } })
      child.on('exit', code => { clearTimeout(timer); reject(new Error(`Harness exited ${code}`)) })
    })
    browser = await chromium.launch({ executablePath: process.env.VIBE_VIDEO_CHROME, headless: true, args: ['--no-sandbox'] })
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    page.setDefaultTimeout(10000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    await page.goto('http://127.0.0.1:3000')
    await page.getByRole('button', { name: '+ Thêm link video' }).waitFor()
    await page.screenshot({ path: path.join(folder, 'desktop.png'), fullPage: true })
    checks.push('Desktop: existing video, lesson context and management controls render')

    await page.getByRole('button', { name: '+ Thêm link video' }).click()
    const dialog = page.getByRole('dialog', { name: 'Thêm link video', exact: true })
    await dialog.waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(folder, 'mobile-form.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true)
    assert.equal(await dialog.getByRole('checkbox').isChecked(), false)
    checks.push('390px: accessible modal, no horizontal overflow; default is internal')

    await dialog.getByLabel('Tên video', { exact: true }).fill('Video thử nghiệm — Lesson 1')
    await dialog.getByLabel('Link video YouTube', { exact: true }).fill('https://example.com/not-a-video')
    await dialog.getByRole('button', { name: 'Lưu link video' }).click()
    await dialog.getByRole('alert').waitFor()
    assert.match(await dialog.getByRole('alert').innerText(), /không hợp lệ/)
    assert.equal(await dialog.getByLabel('Tên video', { exact: true }).inputValue(), 'Video thử nghiệm — Lesson 1')
    checks.push('Invalid URL rejected by actual Server Action; form stays open and preserves input')

    await dialog.getByLabel('Link video YouTube', { exact: true }).fill('https://youtu.be/lmnopqrstuv?si=tracking')
    await dialog.getByLabel('Trình độ liên quan').selectOption(ids.level)
    await dialog.getByLabel('Bài học liên quan').selectOption(ids.lesson)
    await dialog.getByLabel('Nhận xét đi kèm video').fill('Tư thế tay và nhịp phách tiến bộ.')
    await dialog.getByRole('button', { name: 'Lưu link video' }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByText('Đã thêm link video.', { exact: true }).waitFor()
    const added = page.locator('li').filter({ hasText: 'Video thử nghiệm — Lesson 1' })
    await added.waitFor()
    assert.equal(await added.getByRole('link').getAttribute('href'), 'https://www.youtube.com/watch?v=lmnopqrstuv')
    assert.equal(await added.getByRole('link').getAttribute('target'), '_blank')
    assert.equal(await added.getByRole('link').getAttribute('rel'), 'noopener noreferrer')
    await page.reload()
    await page.locator('li').filter({ hasText: 'Video thử nghiệm — Lesson 1' }).waitFor()
    checks.push('Save → SQL → refreshed list → reload preserves title, canonical link and lesson')

    await page.goto('http://127.0.0.1:3000/?role=parent')
    await page.getByRole('link', { name: /Xem video/ }).waitFor()
    assert.equal(await page.getByText('Video thử nghiệm — Lesson 1', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: /Thêm link|Sửa link|Gỡ link/ }).count(), 0)
    checks.push('Parent: internal video absent; no add/edit/remove controls')

    await page.goto('http://127.0.0.1:3000')
    const saved = page.locator('li').filter({ hasText: 'Video thử nghiệm — Lesson 1' })
    await saved.getByRole('button', { name: 'Sửa link' }).click()
    const edit = page.getByRole('dialog', { name: 'Sửa link video', exact: true })
    await edit.getByLabel('Tên video', { exact: true }).fill('Video đã cập nhật — Lesson 1')
    await edit.getByRole('checkbox').check()
    await edit.getByRole('button', { name: 'Lưu link video' }).click()
    await edit.waitFor({ state: 'hidden' })
    await page.getByText('Đã cập nhật link video.', { exact: true }).waitFor()
    await page.goto('http://127.0.0.1:3000/?role=parent')
    await page.getByText('Video đã cập nhật — Lesson 1', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(folder, 'mobile-parent.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    checks.push('Edit and share: parent receives updated link and note; mobile stays within viewport')

    await page.goto('http://127.0.0.1:3000')
    await page.locator('li').filter({ hasText: 'Video đã cập nhật — Lesson 1' }).getByRole('button', { name: 'Gỡ link' }).click()
    const remove = page.getByRole('dialog', { name: 'Gỡ link video', exact: true })
    await remove.getByRole('button', { name: 'Xác nhận gỡ link' }).click()
    await remove.waitFor({ state: 'hidden' })
    await page.getByText('Đã gỡ link khỏi hồ sơ học tập.', { exact: true }).waitFor()
    await page.goto('http://127.0.0.1:3000/?role=parent')
    await page.getByRole('link', { name: /Xem video/ }).waitFor()
    assert.equal(await page.getByText('Video đã cập nhật — Lesson 1', { exact: true }).count(), 0)
    checks.push('Remove: confirmation, successful SQL soft-delete and disappearance from parent view')
    assert.deepEqual(errors, [])
    checks.push('No browser JavaScript or console errors')
    fs.writeFileSync(path.join(folder, 'browser-result.json'), JSON.stringify({ scope: 'Isolated component/action/SQL harness, synthetic identity helpers; not Mac/Supabase E2E', status: 'PASS', checks }, null, 2) + '\n')
    console.log(JSON.stringify({ status: 'PASS', checks }, null, 2))
  } finally {
    if (browser) await browser.close()
    child.kill('SIGTERM')
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
